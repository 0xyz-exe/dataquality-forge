def generate_json_report(validation_data: Dict[str, Any]) -> str:
    return json.dumps(validation_data, indent=2, default=str)


def generate_csv_report(validation_data: Dict[str, Any]) -> str:
    rows = []
    for r in validation_data.get("rule_results", []):
        rows.append({
            "rule_name": r.get("rule_name"),
            "rule_type": r.get("rule_type"),
            "target_columns": ",".join(r.get("target_columns", [])),
            "severity": r.get("severity"),
            "status": "PASSED" if r.get("passed") else "FAILED",
            "total_records": r.get("total_records"),
            "passed_records": r.get("passed_records"),
            "failed_records": r.get("failed_records"),
            "pass_percentage": r.get("pass_percentage"),
            "duration_ms": r.get("duration_ms"),
            "error_message": r.get("error_message") or "",
        })
    df = pd.DataFrame(rows)
    return df.to_csv(index=False)


def generate_html_report(validation_data: Dict[str, Any], dataset_name: str = "Dataset") -> str:
    tmpl = Template(HTML_REPORT_TEMPLATE)
    context = dict(validation_data)
    context["dataset_name"] = dataset_name
    context["generated_at"] = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    context["score_breakdown"] = context.get("score_breakdown") or {"formula": "weighted_passed / weighted_total * 100"}
    return tmpl.render(**context)
